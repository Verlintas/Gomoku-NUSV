    fun t(key: String, language: Language = Language.ZH): String =
        (if (language == Language.ZH) zh else en)[key] ?: key

    fun t(key: String, language: Language, vararg args: Pair<String, String>): String {
        var text = t(key, language)
        args.forEach { (k, v) -> text = text.replace("{$k}", v) }
        return text
    }
